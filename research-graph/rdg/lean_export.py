"""Export the dependency structure as a Lean 4 file that machine-checks what still stands.

Each claim becomes a `Prop`. Unchallenged foundational claims get a truth axiom.
Each methodology/subject edge becomes a premise `sources → claim`. Background
citations are NOT logical premises, so a disproven citation can't break a proof.
Directly challenged claims get no truth axiom.

For every claim that can still be derived, we emit

    theorem <claim>_stands (h : ¬ <disproven>) ... : <claim>

i.e. a proof that the claim holds *even assuming* the challenged findings are false.
Lean verifies the derivation against the model. It cannot check that the model
matches the actual science; that is the human (or LLM-assisted) step.
"""
from __future__ import annotations

import re

from .graph import ResearchGraph
from .models import DependencyKind
from .propagation import ClaimKey

LOGICAL_KINDS = frozenset({DependencyKind.METHODOLOGY, DependencyKind.SUBJECT})


def lean_name(key: ClaimKey) -> str:
    raw = f"{key[0]}__{key[1]}"
    return "c_" + re.sub(r"[^A-Za-z0-9_]", "_", raw)


def premises(graph: ResearchGraph) -> dict[ClaimKey, tuple[ClaimKey, ...]]:
    """Logical premises of each claim. Unmapped edges conservatively need every source claim."""
    prem: dict[ClaimKey, list[ClaimKey]] = {}
    for d in graph.dependencies:
        if d.kind not in LOGICAL_KINDS:
            continue
        src_ids = d.source_claims or graph.papers[d.source_paper].claim_ids
        dep_ids = d.dependent_claims or graph.papers[d.dependent_paper].claim_ids
        for cid in sorted(dep_ids):
            bucket = prem.setdefault((d.dependent_paper, cid), [])
            bucket.extend((d.source_paper, s) for s in sorted(src_ids) if (d.source_paper, s) not in bucket)
    return {k: tuple(v) for k, v in prem.items()}


def challenged(graph: ResearchGraph) -> frozenset[ClaimKey]:
    keys: set[ClaimKey] = set()
    for ch in graph.challenges:
        for cid in ch.claim_ids or graph.papers[ch.paper_id].claim_ids:
            keys.add((ch.paper_id, cid))
    return frozenset(keys)


def derivable(graph: ResearchGraph) -> dict[ClaimKey, bool]:
    prem = premises(graph)
    bad = challenged(graph)
    ok: dict[ClaimKey, bool] = {}
    for pid in graph.topological_order():
        for c in graph.papers[pid].claims:
            key = (pid, c.id)
            ok[key] = key not in bad and all(ok[p] for p in prem.get(key, ()))
    return ok


def _proof_term(key: ClaimKey, prem: dict[ClaimKey, tuple[ClaimKey, ...]]) -> str:
    sources = prem.get(key, ())
    if not sources:
        return f"ax_{lean_name(key)}"
    args = [_proof_term(s, prem) for s in sources]
    arg = args[0] if len(args) == 1 else "⟨" + ", ".join(args) + "⟩"
    return f"(dep_{lean_name(key)} {arg})"


def export(graph: ResearchGraph, namespace: str = "ResearchGraph") -> str:
    prem = premises(graph)
    bad = challenged(graph)
    ok = derivable(graph)
    order = [(pid, c.id) for pid in graph.topological_order() for c in graph.papers[pid].claims]
    texts = {(p.id, c.id): c.text for p in graph.papers.values() for c in p.claims}

    out = ["-- generated by rdg.lean_export; do not edit by hand", f"namespace {namespace}", ""]
    for key in order:
        out.append(f"/-- {key[0]}#{key[1]}: {texts[key].replace('-/', '- /')} -/")
        out.append(f"axiom {lean_name(key)} : Prop")
    out.append("")
    out.append("-- established foundations (unchallenged, no logical premises)")
    for key in order:
        if key not in bad and not prem.get(key):
            out.append(f"axiom ax_{lean_name(key)} : {lean_name(key)}")
    out.append("")
    out.append("-- dependency premises: if the sources hold, the claim holds")
    for key in order:
        srcs = prem.get(key)
        if srcs and key not in bad:
            lhs = " ∧ ".join(lean_name(s) for s in srcs)
            out.append(f"axiom dep_{lean_name(key)} : {lhs} → {lean_name(key)}")
    out.append("")

    hyps = " ".join(f"(_h{i} : ¬ {lean_name(b)})" for i, b in enumerate(sorted(bad)))
    out.append("-- what still stands, even assuming every challenged finding is false")
    for key in order:
        if key in bad:
            out.append(f"-- {lean_name(key)}: directly challenged")
        elif ok[key]:
            out.append(f"theorem {lean_name(key)}_stands {hyps} : {lean_name(key)} :=")
            out.append(f"  {_proof_term(key, prem)}")
        else:
            out.append(f"-- {lean_name(key)}: no derivation avoids the challenged findings")
    out += ["", f"end {namespace}", ""]
    return "\n".join(out)
